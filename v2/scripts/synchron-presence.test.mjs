import assert from 'node:assert/strict'
import {synchronPresence,synchronNavigation,synchronEntryConflict,synchronOwnedEntry,canCancelSynchronOpening,synchronSnapshotMatches,acceptSynchronSnapshot,synchronDiscoveryStatus,synchronRecoveryDecision} from '../src/lib/synchronPresence.js'
const runtime={},entry={actor:'a',runtime,href:'synchron-session:one'}
const snap=(phase,props={})=>({sessionId:'one',revision:2,serverAt:1000,leader:false,isMember:true,joined:true,view:{phase},...props})
assert.equal(synchronPresence(null,null),null)
assert.equal(synchronPresence({href:'bad'},null),null)
assert.equal(synchronPresence(entry,null).locked,true)
assert.equal(synchronPresence(entry,snap('finished',{sessionId:'wrong'})).locked,true)
assert.equal(synchronPresence(entry,snap('ready',{joined:false})).locked,false)
assert.equal(synchronPresence(entry,snap('ready',{leader:true,joined:false})).locked,true)
for(const phase of ['ready','countdown','running','paused']){
 const presence=synchronPresence(entry,snap(phase))
 assert.equal(presence.locked,true)
 assert.equal(synchronNavigation('trening',presence),'synchron-session')
 assert.equal(synchronNavigation('oversikt',presence),'oversikt')
 assert.equal(synchronEntryConflict(entry,presence,'synchron-session:two'),true)
 assert.equal(synchronEntryConflict(entry,presence,entry.href),false)
}
assert.equal(synchronPresence(entry,snap('finished')).locked,false)
assert.equal(synchronNavigation('trening',synchronPresence(entry,snap('finished'))),'trening')
assert.equal(synchronEntryConflict(entry,synchronPresence(entry,snap('finished')),'synchron-session:two'),false)
assert.equal(synchronPresence(entry,snap('other')).locked,true)
assert.equal(synchronPresence(entry,snap('running',{isMember:false,leader:false})).locked,true)
assert.equal(synchronOwnedEntry(entry,'a',runtime),true)
assert.equal(synchronOwnedEntry(entry,'b',runtime),false)
assert.equal(synchronOwnedEntry(entry,'a',{}),false)
assert.equal(synchronOwnedEntry(entry,null,runtime),false)
assert.equal(synchronNavigation('trening',null),'trening')

const origin={actor:'a',runtime,href:entry.href}
assert.equal(canCancelSynchronOpening(entry,synchronPresence(entry,null),origin),true)
for(const phase of ['ready','countdown','running','paused','finished'])assert.equal(canCancelSynchronOpening(entry,synchronPresence(entry,snap(phase)),origin),false)
assert.equal(canCancelSynchronOpening(entry,synchronPresence(entry,null),{...origin,actor:'b'}),false)
assert.equal(canCancelSynchronOpening(entry,synchronPresence(entry,null),{...origin,runtime:{}}),false)
assert.equal(canCancelSynchronOpening(entry,synchronPresence(entry,null),{...origin,href:'synchron-session:two'}),false)
assert.equal(canCancelSynchronOpening(null,null,origin),false)
assert.equal(synchronSnapshotMatches(entry,{...origin,snapshot:snap('running')}),true)
assert.equal(synchronSnapshotMatches(entry,{...origin,snapshot:snap('running',{sessionId:'two'})}),false)
assert.equal(synchronSnapshotMatches(entry,{...origin,actor:'b',snapshot:snap('running')}),false)
assert.equal(synchronSnapshotMatches(entry,{...origin,runtime:{},snapshot:snap('running')}),false)
assert.equal(synchronSnapshotMatches(entry,{...origin,href:'synchron-session:two',snapshot:snap('running')}),false)
assert.equal(synchronSnapshotMatches(entry,{...origin,snapshot:null}),false)

const running=snap('running'),later=snap('running',{serverAt:2000}),paused=snap('paused',{revision:3,serverAt:3000})
assert.equal(acceptSynchronSnapshot(null,entry,{...origin,snapshot:running}),running)
assert.equal(acceptSynchronSnapshot(later,entry,{...origin,snapshot:running}),later)
assert.equal(acceptSynchronSnapshot(running,entry,{...origin,snapshot:later}),later)
assert.equal(acceptSynchronSnapshot(paused,entry,{...origin,snapshot:{...later,serverAt:4000}}),paused)
assert.equal(acceptSynchronSnapshot(later,entry,{...origin,snapshot:paused}),paused)
for(const invalid of [{revision:-1},{revision:NaN},{serverAt:undefined},{joined:'yes'},{view:{phase:'unknown'}},{leader:false,isMember:false}])assert.equal(acceptSynchronSnapshot(running,entry,{...origin,snapshot:{...running,...invalid}}),running)
assert.equal(acceptSynchronSnapshot(running,entry,{...origin,actor:'b',snapshot:paused}),running)

const discoveryRuntime={actorId:'a',discover:async()=>({active:null})},context={actor:'a',runtime:discoveryRuntime}
assert.equal(synchronDiscoveryStatus(null,'a',discoveryRuntime),'pending')
assert.equal(synchronDiscoveryStatus({...context,status:'ready'},'a',discoveryRuntime),'ready')
assert.equal(synchronDiscoveryStatus({...context,status:'ready'},'a',{...discoveryRuntime}),'pending')
assert.equal(synchronDiscoveryStatus({...context,status:'error'},'a',discoveryRuntime),'error')
assert.equal(synchronDiscoveryStatus(null,'a',null),'disabled')
assert.equal(synchronDiscoveryStatus(null,'b',discoveryRuntime),'disabled')
assert.deepEqual(synchronRecoveryDecision({active:null},context),{status:'ready',entry:null,snapshot:null})
const recovered=synchronRecoveryDecision({active:running},context)
assert.equal(recovered.status,'ready');assert.equal(recovered.entry.actor,'a');assert.equal(recovered.entry.runtime,discoveryRuntime);assert.equal(recovered.entry.href,'synchron-session:one');assert.equal(recovered.snapshot,running)
for(const result of [null,{}, {active:null,issue:'offline'},{active:snap('finished')},{active:snap('ready',{joined:false})},{active:snap('running',{revision:-1})},{active:snap('running',{sessionId:'../bad'})},{active:snap('running',{leader:false,isMember:false})}])assert.equal(synchronRecoveryDecision(result,context).status,'error')
assert.equal(synchronRecoveryDecision({active:running},{...context,actor:'b'}).status,'error')
