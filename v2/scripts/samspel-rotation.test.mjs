import assert from 'node:assert/strict'
import {samspelConfig,samspelIssue,samspelRoles,samspelResultIssue,samspelScoring,samspelWithCount,samspelRoundInstruction,samspelWithSwitch,samspelRotation,samspelIsTimed,samspelIsManual,appendSamspelSwap,normalizeSamspelSwaps,samspelParticipantRows,samspelParticipantResults,samspelErgSlots,samspelCapacityIssue,samspelStationLabels} from '../src/lib/samspel.js'
const legacy={version:1,mode:'parallel_round_swap',task:'row',metric:'distance'}
const context={format:'AMRAP',participation:'partner',collaboration:'parallel',items:[{name:'Push-up'}]}
assert.equal(samspelConfig({samspel:legacy}),legacy)
assert.deepEqual(samspelRoles(legacy,0),['Romaskin','AMRAP'])
assert.deepEqual(samspelRoles(legacy,1),['AMRAP','Romaskin'])
assert.equal(samspelIssue(legacy,context),null)
assert.equal(samspelConfig(null),null)
assert.equal(samspelWithCount(legacy,9),null)
for(let count=2;count<=8;count++){
 const config=samspelWithCount(legacy,count)
 assert.equal(samspelConfig({samspel:config}),config)
 assert.equal(samspelIssue(config,{...context,participation:count===2?'partner':'team',participantCount:count}),null)
 const sequence=Array.from({length:count},(_,i)=>samspelRoles(config,i))
 assert.deepEqual(sequence.map(roles=>roles.indexOf('Romaskin')),Array.from({length:count},(_,i)=>i))
 assert.equal(sequence.every(roles=>roles.length===count&&roles.filter(x=>x==='AMRAP').length===count-1),true)
 assert.deepEqual(samspelRoles(config,count),sequence[0])
 assert.deepEqual(samspelRoles(config,Infinity),sequence[0])
}
const team=samspelWithCount(legacy,4)
assert.ok(samspelIssue(team,context))
assert.ok(samspelIssue(team,{...context,participation:'team',participantCount:3}))
assert.ok(samspelIssue(team,{...context,participation:'team',participantCount:4,format:'EMOM'}))
assert.ok(samspelIssue(team,{...context,participation:'team',participantCount:4,items:[]}))
assert.ok(samspelRoundInstruction(team).includes('Alle'))
assert.equal(samspelResultIssue(team,0),null)
assert.ok(samspelResultIssue(team,''))
assert.deepEqual(samspelScoring(team,{}),{type:'multi',fields:['rounds_reps','distance']})
console.log('Samspel rotation checks passed')

const timed=samspelWithSwitch(team,'time',60)
assert.equal(samspelIsTimed(timed),true)
assert.equal(samspelIssue(timed,{...context,participation:'team',participantCount:4}),null)
assert.deepEqual(samspelRotation(timed,{elapsed:0,target:180,rounds:5}),{roles:['Romaskin','AMRAP','AMRAP','AMRAP'],nextSwitchSeconds:60,timed:true})
assert.equal(samspelRotation(timed,{elapsed:59,target:180}).nextSwitchSeconds,1)
assert.equal(samspelRotation(timed,{elapsed:60,target:180}).roles[1],'Romaskin')
assert.deepEqual(samspelRotation(timed,{elapsed:60,target:180,rounds:99}),samspelRotation(timed,{elapsed:60,target:180,rounds:0}))
assert.equal(samspelRotation(timed,{elapsed:120,target:180}).nextSwitchSeconds,null)
assert.equal(samspelRotation(timed,{elapsed:180,target:180}).roles[2],'Romaskin')
assert.equal(samspelRotation(timed,{elapsed:200,target:180}).roles[2],'Romaskin')
assert.equal(samspelRotation(timed,{elapsed:60,target:60}).roles[0],'Romaskin')
assert.ok(samspelIssue(samspelWithSwitch(team,'time',14),{...context,participation:'team',participantCount:4}))
assert.ok(samspelIssue(samspelWithSwitch(team,'time',601),{...context,participation:'team',participantCount:4}))
assert.ok(samspelIssue(samspelWithSwitch(team,'time',15.5),{...context,participation:'team',participantCount:4}))
assert.equal(samspelIsTimed(samspelWithSwitch(timed,'round')),false)
assert.equal(samspelRotation(legacy,{elapsed:300,rounds:1}).roles[1],'Romaskin')
console.log('Timed Samspel swap checks passed')

const manual=samspelWithSwitch(team,'manual')
const action={elapsed:10,running:true,target:180}
assert.equal(samspelIsManual(manual),true)
assert.equal(samspelIsTimed(manual),false)
assert.equal(samspelIssue(manual,{...context,participation:'team',participantCount:4}),null)
assert.deepEqual(appendSamspelSwap(manual,[],action),[10])
assert.deepEqual(appendSamspelSwap(manual,[10],action),[10])
assert.deepEqual(appendSamspelSwap(manual,[10],{...action,elapsed:11}),[10])
assert.deepEqual(appendSamspelSwap(manual,[10],{...action,elapsed:12}),[10,12])
assert.deepEqual(appendSamspelSwap(manual,[10],{...action,elapsed:20,running:false}),[10])
assert.deepEqual(appendSamspelSwap(manual,[10],{...action,elapsed:180}),[10])
assert.deepEqual(appendSamspelSwap(timed,[],action),[])
assert.deepEqual(normalizeSamspelSwaps([10,10,9,11,12,'14',null,Infinity,20]),[10,12,20])
assert.deepEqual(normalizeSamspelSwaps(null),[])
assert.equal(samspelRotation(manual,{manualSwaps:[10,20],rounds:99,elapsed:60}).roles[2],'Romaskin')
assert.deepEqual(samspelRotation(manual,{manualSwaps:[10],rounds:99,elapsed:60}),samspelRotation(manual,{manualSwaps:[10],rounds:0,elapsed:0}))
assert.equal(samspelRotation(manual,{manualSwaps:[10,20].slice(0,-1)}).roles[1],'Romaskin')
assert.equal(samspelRotation(manual,{manualSwaps:[]}).roles[0],'Romaskin')
assert.equal(samspelIsManual(samspelWithSwitch(manual,'round')),false)
console.log('Manual Samspel swap checks passed')

const scoredTeam={...manual,individual_scores:true}
assert.equal(samspelParticipantRows(scoredTeam).length,4)
assert.deepEqual(samspelParticipantRows(manual),[])
assert.deepEqual(samspelParticipantResults(scoredTeam,{}),{rows:[],issue:null})
assert.deepEqual(samspelParticipantResults(scoredTeam,{1:{rounds:'0',reps:'',erg:'400.5'},3:{rounds:'2',reps:'7'},9:{rounds:'9'}}),{rows:[{slot:1,rounds:0,extra_reps:null,erg_value:400.5},{slot:3,rounds:2,extra_reps:7,erg_value:null}],issue:null})
assert.ok(samspelParticipantResults(scoredTeam,{1:{rounds:'1.5'}}).issue)
assert.ok(samspelParticipantResults(scoredTeam,{1:{reps:'-1'}}).issue)
assert.ok(samspelParticipantResults(scoredTeam,{1:{erg:'Infinity'}}).issue)
assert.deepEqual(samspelParticipantResults(null,{1:{rounds:'4'}}),{rows:[],issue:null})
assert.deepEqual(samspelParticipantResults(manual,{1:{rounds:'4'}}),{rows:[],issue:null})
assert.equal(samspelParticipantRows({...legacy,individual_scores:true}).length,2)
console.log('Participant-slot score checks passed')

const dual={...team,erg_slots:2,available_ergs:2}
const teamContext={...context,participation:'team',participantCount:4}
assert.equal(samspelCapacityIssue(dual),null)
assert.equal(samspelIssue(dual,teamContext),null)
assert.ok(samspelIssue({...dual,available_ergs:1},teamContext))
assert.ok(samspelIssue({...dual,available_ergs:null},teamContext))
assert.ok(samspelIssue({...dual,erg_slots:4},teamContext))
assert.ok(samspelIssue({...dual,erg_slots:0},teamContext))
assert.ok(samspelIssue({...dual,available_ergs:2.5},teamContext))
assert.equal(samspelErgSlots(legacy),1)
assert.deepEqual(samspelRoles(dual,0),['Romaskin','Romaskin','AMRAP','AMRAP'])
assert.deepEqual(samspelStationLabels(dual,samspelRoles(dual,3)),['Romaskin 2','AMRAP','AMRAP','Romaskin 1'])
assert.deepEqual(samspelRotation(samspelWithSwitch(dual,'time',60),{elapsed:60,target:180}).roles,samspelRoles(dual,1))
assert.deepEqual(samspelRotation(samspelWithSwitch(dual,'manual'),{manualSwaps:[10,20],rounds:99}).roles,samspelRoles(dual,2))
for(let count=2;count<=8;count++)for(let slots=1;slots<count;slots++){
 const config={...samspelWithCount(legacy,count),erg_slots:slots,available_ergs:slots}
 const rotations=Array.from({length:count},(_,i)=>samspelRoles(config,i))
 assert.equal(rotations.every(roles=>roles.filter(x=>x==='Romaskin').length===slots),true)
 assert.equal(Array.from({length:count},(_,i)=>rotations.filter(roles=>roles[i]==='Romaskin').length).every(n=>n===slots),true)
 assert.equal(rotations.every(roles=>new Set(samspelStationLabels(config,roles).filter(x=>x!=='AMRAP')).size===slots),true)
}
console.log('Concurrent station and capacity checks passed')
