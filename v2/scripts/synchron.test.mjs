import assert from 'node:assert/strict'
import {createSynchronSession,applySynchronCommand,synchronPlanIssue,synchronClock,synchronAssignedTime,synchronEstimate,synchronAllocate} from '../src/lib/synchron.js'
const plan={id:'four-fronts',leaderId:'pt',members:['a','b'],movements:[['step','reps',100,'estimate'],['hang','seconds',180,'clock'],['wall','reps',150,'estimate'],['row','meters',2000,'hybrid'],['cal','calories',60,'machine']].map(([id,unit,target,method])=>({id,exerciseId:id,unit,target,method,collaboration:'relay',doses:{a:{variant:'standard',loadKg:9},b:{variant:'scaled',loadKg:4}}}))}
assert.equal(synchronPlanIssue(plan),null)
assert.ok(synchronPlanIssue({...plan,members:['a','a']}))
assert.ok(synchronPlanIssue({...plan,movements:[{...plan.movements[0],unit:'seconds'}]}))
let s=createSynchronSession(plan),n=0
const act=(type,actorId,at,more={})=>{const result=applySynchronCommand(s,{id:'e'+(++n),revision:s.revision,type,...more},{actorId,at});assert.equal(result.issue,null);s=result.state}
const reject=(type,actorId,at,more={})=>{const result=applySynchronCommand(s,{id:'bad'+(++n),revision:s.revision,type,...more},{actorId,at});assert.ok(result.issue);assert.equal(result.state,s)}
reject('start','a',0,{memberId:'a'})
act('join','a',0)
act('join','b',1)
reject('start','a',2,{memberId:'a'})
act('start','pt',1000,{memberId:'a'})
reject('takeover','b',10500)
assert.equal(synchronClock(s,11000),0)
act('takeover','b',41000)
assert.equal(synchronAssignedTime(s,'step','a'),30)
reject('takeover','a',41500)
act('idle','b',61000)
act('takeover','a',71000)
act('load','a',81000,{loadKg:12})
act('pause','pt',91000)
act('resume','pt',101000)
act('advance','pt',111000,{actual:100})
assert.equal(synchronAssignedTime(s,'step','a'),60)
assert.equal(synchronAssignedTime(s,'step','b'),20)
assert.equal(s.segments.length,5)
assert.equal(s.totals.step.actual,100)
assert.equal(s.active,null)
assert.equal(plan.movements[0].doses.a.loadKg,9)
const cal=[{memberId:'a',exerciseId:'step',variant:'standard',loadKg:9,unit:'reps',source:'observed',perMinute:24},{memberId:'a',exerciseId:'step',variant:'standard',loadKg:12,unit:'reps',source:'observed',perMinute:18}]
assert.equal(synchronEstimate(s,'step','a',cal).value,22)
assert.equal(synchronEstimate(s,'step','a',cal).prEligible,false)
assert.equal(synchronEstimate(s,'step','a',cal.slice(0,1)),null)
assert.equal(synchronEstimate(s,'step','b',cal),null)
act('takeover','b',115000)
act('idle','b',135000)
act('advance','pt',140000,{actual:20})
assert.equal(synchronAssignedTime(s,'hang','b'),20)
assert.equal(synchronEstimate(s,'hang','b',cal),null)
reject('finish','pt',141000,{actual:0})
act('finish','pt',141000,{actual:null,abort:true})
assert.equal(s.phase,'finished')
assert.equal(s.totals.wall.actual,null)
assert.equal(s.totals.row,undefined)
const replay=applySynchronCommand(s,{id:s.events[0].id,revision:0,type:'join'},{actorId:'a',at:0})
assert.equal(replay.duplicate,true)
assert.equal(replay.state,s)
assert.ok(applySynchronCommand(s,{id:'new',revision:0,type:'join'},{actorId:'a',at:150000}).issue)
assert.deepEqual(synchronAllocate(150,[{memberId:'a',estimate:80},{memberId:'b',estimate:55}]).map(x=>x.value),[89,61])
assert.deepEqual(synchronAllocate(150,[{memberId:'a',actual:80},{memberId:'b',estimate:55}]).map(x=>x.value),[80,70])
assert.equal(synchronAllocate(150,[{memberId:'a',actual:160},{memberId:'b',estimate:55}]),null)
assert.equal(synchronAllocate(150,[{memberId:'a',estimate:80},{memberId:'b',estimate:null}]),null)
assert.equal(synchronAllocate(0,[{memberId:'a',estimate:0},{memberId:'b',estimate:0}])[0].value,0)
assert.ok(synchronAllocate(100,[{memberId:'a',estimate:33},{memberId:'b',estimate:33},{memberId:'c',estimate:33}]).every(x=>x.quality==='estimated'&&!x.prEligible))
