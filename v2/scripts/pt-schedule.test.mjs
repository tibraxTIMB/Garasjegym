import assert from 'node:assert/strict'
import {slotDate,dateSlot,weekStart,osloDay,appointmentTime,makePlanRows,makeDirectRows,calendarEntries,entriesForDay,canMovePlan,canMoveDirect,validDate} from '../src/lib/ptSchedule.js'
const program={id:'p',client_id:'c',status:'active',start_date:'2026-11-30',weeks:6,flow_unlock_mode:'date'}
const wod={id:'w',name:'Test',duration_minutes:18}
assert.equal(slotDate(program,2,3),'2026-12-09')
assert.deepEqual(dateSlot(program,'2026-12-09'),{week:2,day:3})
assert.equal(weekStart('2026-11-26'),'2026-11-23')
assert.equal(osloDay('2026-11-26T23:30:00Z'),'2026-11-27')
assert.equal(appointmentTime('2026-11-26T16:00:00Z'),'17:00')
assert.equal(validDate('2026-02-30'),false)
const rows=makePlanRows({program,existing:[{program_id:'p',sequence_no:8}],wods:[wod,{...wod,id:'w2'}],week:2,day:3,date:'2026-12-09',time:'17:00',memberId:'c'})
assert.deepEqual(rows.map(r=>r.sequence_no),[9,10])
assert.deepEqual(rows.map(r=>r.workout_snapshot.schedule_time),['17:00','17:00'])
assert.throws(()=>makePlanRows({program,wods:[wod],week:2,day:3,date:'2026-12-08',memberId:'c'}))
assert.throws(()=>makePlanRows({program,wods:[wod],week:2,day:3,date:'2026-12-09',memberId:'other'}))
assert.throws(()=>makePlanRows({program,wods:[wod],week:2,day:3,date:'',time:'17:00',memberId:'c'}))
const direct=makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],deadline:'2026-12-09'})
assert.equal(direct[0].due_date,'2026-12-09')
assert.equal(direct[0].linked_session_id,null)
assert.throws(()=>makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],appointment:{id:'s',client_id:'other',status:'planned',starts_at:'2026-12-09T16:00:00Z'}}))
assert.equal(canMovePlan({status:'completed'}),false)
assert.equal(canMovePlan({status:'planned',workout_log_id:'r'}),false)
assert.equal(canMovePlan({status:'planned'}),true)
assert.deepEqual(calendarEntries({program,plan:[{...rows[0],id:'s'}],assignments:[{...direct[0],id:'a',wods:wod}]}).map(x=>[x.key,x.date,x.deadline??false]),[['plan:s','2026-12-09',false],['assignment:a','2026-12-09',true]])
console.log('PT schedule: 18 checks passed')

const standalone=makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],scheduleDate:'2026-12-09',scheduleTime:'17:15'})
assert.equal(standalone[0].scheduled_date,'2026-12-09')
assert.equal(standalone[0].scheduled_time,'17:15')
assert.equal(standalone[0].due_date,null)
assert.equal(standalone[0].linked_session_id,null)
assert.throws(()=>makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],scheduleTime:'17:15'}))
assert.throws(()=>makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],scheduleDate:'2026-12-09',scheduleTime:'25:15'}))
assert.throws(()=>makeDirectRows({memberId:'c',actorId:'pt',wods:[wod],scheduleDate:'2026-12-09',appointment:{id:'s',client_id:'c',status:'planned',starts_at:'2026-12-09T16:00:00Z'}}))
assert.equal(calendarEntries({assignments:[{...standalone[0],id:'a',scheduled_time:'17:15:00',wods:wod}]} )[0].time,'17:15')
assert.equal(canMoveDirect({status:'assigned',scheduled_date:null}),true)
assert.equal(canMoveDirect({status:'completed',scheduled_date:'2026-12-09'}),false)
assert.equal(canMoveDirect({status:'assigned',linked_session_id:'s',scheduled_date:null}),false)
console.log('PT schedule: 11 standalone timing checks passed')

// One assignment keeps one calendar entry even when scheduled time and deadline differ.
const timedWithDeadline={...standalone[0],id:'a2',due_date:'2026-12-11',wods:wod}
const timedEntries=calendarEntries({assignments:[timedWithDeadline]})
assert.equal(timedEntries.length,1)
assert.deepEqual([timedEntries[0].date,timedEntries[0].time,timedEntries[0].dueDate,timedEntries[0].deadline],['2026-12-09','17:15','2026-12-11',false])
const linkedEntries=calendarEntries({assignments:[{...direct[0],id:'a3',linked_session_id:'pt1',wods:wod}],appointments:[{id:'pt1',starts_at:'2026-12-08T16:30:00Z',status:'planned'}]})
const linkedAssignment=linkedEntries.find(e=>e.kind==='assignment')
assert.deepEqual([linkedAssignment.date,linkedAssignment.time,linkedAssignment.dueDate],['2026-12-08','17:30','2026-12-09'])
assert.equal(calendarEntries({assignments:[{...direct[0],id:'a4'}]})[0].deadline,true)
