export const INVENTORY_GROUPS=['stong','ez-stong','vektskiver','manualar','kettlebell','medisinball','squat rack','racktilbehøyr','benk','dips','landmine','trx','plyoboks','romaskin','matte','hoppetau','ab mat','vegg','plattform','strikk','foam roller','pinne','rom og drift','anna']
const norm=v=>String(v??'').trim().toLowerCase().replace(/\s+/g,' ')
const aliases={'vektstong':'stong','barbell':'stong','dumbbell':'manualar','dumbbells':'manualar','manual':'manualar','kettlebells':'kettlebell','kasse':'plyoboks','pull-up-stong':'squat rack','pullupbar':'squat rack','medball':'medisinball','wall ball':'medisinball','skråbenk':'benk','flat benk':'benk','roing':'romaskin'}
export function inventoryGroup(value){const key=norm(value);return aliases[key]||key}
export function inventoryFromRows(rows=[]){
 const result=Object.create(null),groups=new Map()
 const known=v=>Number.isSafeInteger(v)&&v>=0&&v<=999
 for(const row of rows){
  if(!row?.equipment_key)continue
  if(row.inventory_kind!=='item'){if(known(row.available))result[norm(row.equipment_key)]=row.available;continue}
  const group=inventoryGroup(row.group_key)
  if(!group)continue
  if(!groups.has(group))groups.set(group,[])
  groups.get(group).push(row.available)
 }
 for(const [group,counts] of groups){
  const keys=[group,...Object.keys(aliases).filter(k=>aliases[k]===group)]
  const sum=counts.reduce((a,b)=>a+(known(b)?b:0),0)
  for(const key of keys)result[key]=counts.every(known)&&sum<=999?sum:null
 }
 return {...result}
}
export function inventoryDraft(values){
 const label=String(values.equipment_label??'').trim(),group=inventoryGroup(values.group_key),notes=String(values.notes??'').trim()
 const qty=String(values.available??'').trim(),weight=String(values.weight_kg??'').trim().replace(',','.')
 if(!label||label.length>160||!INVENTORY_GROUPS.includes(group)||notes.length>1000)throw Error('Kontroller namn, kategori og merknad.')
 if(qty!==''&&(!/^\d+$/.test(qty)||Number(qty)>999))throw Error('Mengda må vera eit heilt tal frå 0 til 999, eller ukjend.')
 if(weight!==''&&(!Number.isFinite(Number(weight))||Number(weight)<=0||Number(weight)>1000))throw Error('Oppgi gyldig vekt i kg, eller la feltet stå tomt.')
 return {inventory_kind:'item',equipment_label:label,group_key:group,available:qty===''?null:Number(qty),weight_kg:weight===''?null:Number(weight),notes}
}
export function missingInitialInventory(rows=[]){
 const existing=new Set(rows.map(r=>r.equipment_key))
 return INITIAL_INVENTORY.filter(r=>!existing.has(r.equipment_key))
}

// Split composite requirements for note visibility only, never for automatic capacity.
export function inventoryNotes(items=[],rows=[]){
 const groups=new Set(items.flatMap(item=>String(item?.equipment||'').split('/').map(inventoryGroup)).filter(Boolean))
 // A rack or barbell workout may encounter the unsafe rack attachments.
 if(groups.has('stong')||groups.has('squat rack'))groups.add('racktilbehøyr')
 return rows.filter(r=>r.inventory_kind==='item'&&r.notes&&groups.has(inventoryGroup(r.group_key))&&r.available!==0)
}
